const fs = require('node:fs');
const http = require('node:http');
const path = require('node:path');
const crypto = require('node:crypto');
const { createRequire } = require('node:module');
const candidate = '/Users/zhangping/DEV/clpm-remediation-20261017';
const ownRequire = createRequire(candidate + '/e2e/package.json');
const ts = ownRequire('typescript');
const out = __dirname;
const filename = candidate + '/e2e/tests/critical-business.spec.ts';
const source = fs.readFileSync(filename, 'utf8');
const tree = ts.createSourceFile(filename, source, ts.ScriptTarget.Latest, true);
const names = ['applicationRoute', 'applicationRouteUrl', 'isAuthenticatedLanding'];
const functions = tree.statements.filter(node => ts.isFunctionDeclaration(node) && names.includes(node.name?.text));
if (functions.length !== 3) throw new Error('Exactly the three current real source helpers are required');
const selected = functions.map(node => node.getText(tree)).join('\n\n');
const javascript = ts.transpileModule(selected, { compilerOptions: { target: ts.ScriptTarget.ES2022 } }).outputText;
fs.writeFileSync(path.join(out, 'helpers.source.ts'), selected, { flag: 'wx' });
fs.writeFileSync(path.join(out, 'helpers.source.js'), javascript, { flag: 'wx' });
fs.writeFileSync(path.join(out, 'source-before.json'), JSON.stringify({ path: filename, sha256: crypto.createHash('sha256').update(source).digest('hex'), extractedNames: names, scope: 'Only pure route helpers; no test registration, app, API or auth code executed' }, null, 2), { flag: 'wx' });
const html = `<!doctype html><meta charset="utf-8"><title>Independent route fixture</title><h1>Independent route fixture</h1><pre id="route"></pre><script>${javascript}\nwindow.helpers={applicationRoute,applicationRouteUrl,isAuthenticatedLanding};function render(){const route=applicationRoute(new URL(location.href));document.querySelector('#route').textContent=JSON.stringify({origin:location.origin,path:route.pathname,query:Object.fromEntries(route.searchParams),routeOrigin:route.origin},null,2)}render();addEventListener('hashchange',render);</script>`;
fs.writeFileSync(path.join(out, 'fixture.html'), html, { flag: 'wx' });
const server = http.createServer((request, response) => {
  fs.appendFileSync(path.join(out, 'server-requests.jsonl'), JSON.stringify({at: new Date().toISOString(), method: request.method, url: request.url}) + '\n');
  response.writeHead(200, { 'Content-Type': 'text/html; charset=utf-8' }); response.end(html);
});
server.listen(0, '127.0.0.1', () => {
  const ready = {at: new Date().toISOString(), pid: process.pid, address: server.address(), productServiceTouched: false};
  fs.writeFileSync(path.join(out, 'server-ready.json'), JSON.stringify(ready, null, 2), { flag: 'wx' });
  console.log(JSON.stringify(ready));
});
for (const signal of ['SIGINT','SIGTERM']) process.on(signal, () => server.close(() => { fs.writeFileSync(path.join(out, 'server-closed.json'), JSON.stringify({at:new Date().toISOString(),signal,closed:true,pid:process.pid}), {flag:'wx'});process.exit(0); }));
