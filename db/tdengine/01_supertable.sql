-- 数据库名: clpm_ts
-- 脚本版本: v3.0
-- 创建日期: 2026-06-21
-- 对应 DDS 版本: DDS v3.0 (产品化架构重构版) §3.1
-- 设计依据: PRD v3.0, FDS v3.0, ADS v3.0
-- 说明: 本脚本遵循 ADS v3.0 "存算分离" 原则，承载高频时序域数据模型。
--       采用 TDengine "一个设备一张表，一类设备一个超级表" 设计模式，
--       覆盖 7 个 OPC Tag 字段（PV/SP/OP/MODE/PID_P/PID_I/PID_D）及 PV 质量码。
-- =============================================================================

-- =============================================================================
-- 1. 创建数据库
-- =============================================================================
-- 参数说明:
--   KEEP 365      —— 原始秒级数据保留 365 天（1 年），对齐 DDS §4.3 留存期策略
--   DURATION 10   —— 数据文件存储周期 10 天（TDengine 3.x 使用 DURATION，对应 2.x 的 DAYS 参数）
--   PRECISION 'ms' —— 时间戳精度为毫秒，满足秒级采样 + 毫秒级写入需求
-- =============================================================================
CREATE DATABASE IF NOT EXISTS clpm_ts KEEP 365 DURATION 10 PRECISION 'ms';

USE clpm_ts;

-- =============================================================================
-- 2. 创建超级表 st_loop_data
-- =============================================================================
-- 对齐 DDS v3.0 §3.1 超级表定义
-- 字段覆盖 7 个 OPC Tag 的原始秒级数据及 PV 质量码
-- =============================================================================
-- 注意：TDengine 3.3.x entrypoint 用 `taos -f` 逐行执行本文件，
-- CREATE STABLE/TABLE 必须写成单行，多行会被拆开逐行提交报
-- "Incomplete SQL statement"，导致 st_loop_data 超级表缺失（fresh 部署必现）。
CREATE STABLE IF NOT EXISTS st_loop_data (ts TIMESTAMP, pv FLOAT, sp FLOAT, op FLOAT, mode TINYINT, pid_p FLOAT, pid_i FLOAT, pid_d FLOAT, pv_quality TINYINT) TAGS (loop_id BINARY(36), unit_id BINARY(36));

-- =============================================================================
-- 3. 子表实例化示例
-- =============================================================================
-- 子表命名规范: d_loop_<位号去分隔符小写>
-- 系统每同步接入一条新回路，将自动执行建表操作
-- =============================================================================

-- 3.1 加氢精制反应器入口温度（HDS-RX-TIC-101）
--     对应回路 L001，所属单元 HDS-RX（反应系统）
CREATE TABLE IF NOT EXISTS d_loop_hds_rx_tic_101
    USING st_loop_data
    TAGS ('00000000-0000-0000-0000-000000000201', '00000000-0000-0000-0000-000000000111');

-- 3.2 加氢精制分馏塔进料流量（HDS-FR-FIC-201）
--     对应回路 L002，所属单元 HDS-FR（分馏系统）
CREATE TABLE IF NOT EXISTS d_loop_hds_fr_fic_201
    USING st_loop_data
    TAGS ('00000000-0000-0000-0000-000000000202', '00000000-0000-0000-0000-000000000112');

-- 3.3 加氢裂化反应器入口温度（HDC-RX-TIC-301）
--     对应回路 L003，所属单元 HDC-RX（反应系统）
CREATE TABLE IF NOT EXISTS d_loop_hdc_rx_tic_301
    USING st_loop_data
    TAGS ('00000000-0000-0000-0000-000000000203', '00000000-0000-0000-0000-000000000113');

